export function accountLabel(value) {
  return Object.hasOwn(accountLabels, value) ? accountLabels[value] : value;
}

export function accountText(value) {
  const prefix = value.match(/^\([^)]+\)\s*(?:-\s*)?/)?.[0] || "";
  const suffix = value.match(/\(([^()]*(?:\([^()]*\)[^()]*)*)\)\s*$/)?.[0] || "";
  const name = value.slice(prefix.length, suffix ? value.lastIndexOf(suffix) : undefined).trim();
  return `${prefix}${accountLabel(name)}${suffix ? ` (${accountLabel(suffix.slice(1, -1))})` : ""}`;
}
